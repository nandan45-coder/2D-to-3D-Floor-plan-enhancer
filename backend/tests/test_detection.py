# --- Wall detection -----------------------------------------------------------


def test_detect_walls_finds_expected_count_on_cottage(cottage_preprocessed):
    walls, openings, thin_lines = detector.detect_walls(cottage_preprocessed.working_image)
    # 4 exterior perimeter walls + 1 interior dividing wall
    assert len(walls) == 5
    assert sum(1 for w in walls if w.wall_type == "exterior") == 4
    assert sum(1 for w in walls if w.wall_type == "interior") == 1


def test_detect_walls_finds_expected_count_on_studio(studio_preprocessed):
    walls, openings, thin_lines = detector.detect_walls(studio_preprocessed.working_image)
    assert len(walls) == 4
    assert all(w.wall_type == "exterior" for w in walls)


def test_thin_dimension_line_excluded_from_walls(cottage_preprocessed):
    """The 1px dimension line under the building must not be reported as a wall."""
    walls, openings, thin_lines = detector.detect_walls(cottage_preprocessed.working_image)
    for wall in walls:
        assert wall.thickness_px >= detector.MIN_WALL_THICKNESS_PX
    # ...but it should still be captured as dimension-line candidate geometry.
    assert len(thin_lines) >= 1


def test_interior_wall_classified_correctly_despite_spanning_most_of_the_height(cottage_preprocessed):
    """
    Regression test: an earlier version of classify_exterior_interior checked
    a wall's coordinates against ALL four boundary extents rather than just
    its own perpendicular axis, which misclassified the interior dividing
    wall (it spans nearly the full building height, like real exterior walls
    do) as exterior.
    """
    walls, openings, thin_lines = detector.detect_walls(cottage_preprocessed.working_image)
    interior_walls = [w for w in walls if w.wall_type == "interior"]
    assert len(interior_walls) == 1
    assert interior_walls[0].orientation == "vertical"


def test_nearby_offsets_straddling_bucket_boundary_still_merge():
    """
    Regression test: naive round(offset / tolerance) bucketing split two
    genuinely close line offsets (e.g. 682.0 and 684.3 with tolerance=8)
    into separate walls because they rounded to different buckets. Chained
    proximity clustering must not have this failure mode.
    """
    close_segments = [
        detector.RawSegment(10.0, 682.0, 10.0, 700.0),
        detector.RawSegment(10.0, 684.3, 10.0, 720.0),
    ]
    groups = detector._cluster_by_proximity(close_segments, lambda s: s.x1, tolerance=8.0)
    assert len(groups) == 1


