def test_ocr_text_does_not_produce_false_stair_detection(cottage_preprocessed):
    """
    Regression test: room-label text ('Living Room', 'Bedroom') sitting at a
    consistent y-height was originally clustered by the stair heuristic into
    a false-positive stair region spanning almost the full building width.
    """
    img = cottage_preprocessed.working_image
    wall_mask = detector.isolate_wall_mask(img)
    stairs = detector.detect_stairs(img, wall_mask)
    for stair in stairs:
        xs = [p[0] for p in stair.polygon_px]
        width = max(xs) - min(xs)
        assert width <= detector.STAIR_MAX_ALONG_EXTENT_PX


# --- OCR ------------------------------------------------------------------


def test_ocr_extracts_room_labels_and_dimension(cottage_preprocessed):
    blocks = ocr_service.extract_text_blocks(cottage_preprocessed.grayscale_image)
    texts = [b.text for b in blocks]
    assert any("Living" in t and "Room" in t for t in texts)
    assert any("Bedroom" in t for t in texts)
    assert any("24" in t for t in texts)


def test_ocr_backend_is_reported(cottage_preprocessed):
    ocr_service.extract_text_blocks(cottage_preprocessed.grayscale_image)
    backend = ocr_service.get_ocr_backend_name()
    assert backend in ("easyocr", "tesseract", "none")


def test_multiword_room_label_not_fragmented(cottage_preprocessed):
    """
    Regression test: Tesseract returns per-word boxes; an earlier version
    treated each word as its own block, so 'Living Room' (two words) never
    matched the 'living room' keyword phrase as a whole.
    """
    blocks = ocr_service.extract_text_blocks(cottage_preprocessed.grayscale_image)
    classified = ocr_service.classify_text_blocks(blocks)
    room_labels = [c for c in classified if c.kind == "room_label"]
    assert any(c.block.text.strip().lower() == "living room" for c in room_labels)


def test_same_row_labels_not_merged_into_one_block(cottage_preprocessed):
    """
    Regression test: Tesseract's own line-grouping merged 'Living Room' and
    'Bedroom' into a single line because they sit at the same y-height. The
    large horizontal gap between them must cause a split.
    """
    blocks = ocr_service.extract_text_blocks(cottage_preprocessed.grayscale_image)
    classified = ocr_service.classify_text_blocks(blocks)
    room_labels = [c for c in classified if c.kind == "room_label"]
    label_texts = {c.block.text.strip().lower() for c in room_labels}
    assert "living room" in label_texts
    assert "bedroom" in label_texts
    assert "living room bedroom" not in label_texts


def test_dimension_pattern_parses_common_formats():
    assert ocr_service._parse_dimension_value("24 ft") == 24.0
    assert ocr_service._parse_dimension_value("24") == 24.0
    assert ocr_service._parse_dimension_value("3.5m") == 3.5
    assert ocr_service._parse_dimension_value("12'-6\"") == pytest.approx(12.5, abs=0.01)
    assert ocr_service._parse_dimension_value("Bedroom") is None


def test_room_label_association_by_point_in_polygon(cottage_preprocessed):
    img = cottage_preprocessed.working_image
    walls, opening_candidates, thin_lines = detector.detect_walls(img)
    rooms = detector.detect_rooms(walls, img.shape)
    room_dicts = [{"id": r.id, "polygon_px": r.polygon_px} for r in rooms]

    blocks = ocr_service.extract_text_blocks(cottage_preprocessed.grayscale_image)
    classified = ocr_service.classify_text_blocks(blocks)
    ocr_service.associate_room_labels(room_dicts, classified)

    names = {rd.get("name") for rd in room_dicts}
    assert "Living Room" in names
    assert "Bedroom" in names


def test_dimension_matched_to_thin_line_geometry(cottage_preprocessed):
    img = cottage_preprocessed.working_image
    walls, opening_candidates, thin_lines = detector.detect_walls(img)
    blocks = ocr_service.extract_text_blocks(cottage_preprocessed.grayscale_image)
    classified = ocr_service.classify_text_blocks(blocks)
    dims = ocr_service.associate_dimensions(classified, thin_lines)

    assert len(dims) == 1
    assert dims[0]["value"] == 24.0
    assert dims[0]["matched_to_geometry"] is True


# --- Postprocessing / calibration ----------------------------------------------


def test_calibration_prefers_ocr_match_over_fallback():
    result = postprocessing.calibrate_scale([(24.0, 480.0)], fallback_reference_px_length=999.0)
    assert result.source == "ocr_dimension_match"
    assert result.pixels_per_unit == pytest.approx(20.0)
    assert result.note is None


def test_calibration_falls_back_when_no_dimension_matched():
    result = postprocessing.calibrate_scale([], fallback_reference_px_length=600.0)
    assert result.source == "fallback_default_assumption"
    assert result.note is not None
    assert result.pixels_per_unit == pytest.approx(600.0 / postprocessing.FALLBACK_ASSUMED_WIDTH_UNITS)


def test_calibration_last_resort_when_nothing_available():
    result = postprocessing.calibrate_scale([], fallback_reference_px_length=None)
    assert result.source == "fallback_default_assumption"
    assert result.pixels_per_unit == 1.0
    assert "uncalibrated" in result.note


def test_wall_confidence_within_valid_range(cottage_preprocessed):
    walls, openings, thin_lines = detector.detect_walls(cottage_preprocessed.working_image)
    for wall in walls:
        confidence = postprocessing.score_wall_confidence(wall)
        assert 0.0 <= confidence <= 1.0


def test_opening_confidence_uses_tier2_ceiling():
    swing_opening = detector.OpeningDetection(
        id="door-x", kind="door", wall_id="wall-x", position=0.5, width_px=60, swing_detected=True
    )
    no_swing_opening = detector.OpeningDetection(
        id="door-y", kind="door", wall_id="wall-x", position=0.5, width_px=60, swing_detected=False
    )
    assert postprocessing.score_opening_confidence(swing_opening) < 1.0
    assert postprocessing.score_opening_confidence(no_swing_opening) < postprocessing.score_opening_confidence(swing_opening)


