def test_full_pipeline_dimension_calibration_is_reasonably_accurate():
    """
    The cottage is drawn as a 24ft-wide building with an OCR-readable '24 ft'
    label. After calibration, the detected building width (max_x - min_x
    across wall endpoints) should be close to 24 units -- not exact, given
    Hough imprecision, but within a generous tolerance.
    """
    fp_dict = detector.run_detection_pipeline(str(COTTAGE_PATH), "TEST-COTTAGE")
    xs = [pt["x"] for wall in fp_dict["walls"] for pt in (wall["start"], wall["end"])]
    detected_width = max(xs) - min(xs)
    assert detected_width == pytest.approx(24.0, abs=2.0)


