def test_full_pipeline_door_and_window_height_fields_always_null():
    """
    Regression / design-fidelity test: per DETECTION_PIPELINE.md Section 5,
    vertical dimensions (height, sill_height) are not visible in a top-down
    2D plan and must never be populated by this pipeline.
    """
    fp_dict = detector.run_detection_pipeline(str(COTTAGE_PATH), "TEST-COTTAGE")
    for door in fp_dict["doors"]:
        assert door["height"] is None
    for window in fp_dict["windows"]:
        assert window["height"] is None
        assert window["sill_height"] is None
    for wall in fp_dict["walls"]:
        assert wall["height"] is None


